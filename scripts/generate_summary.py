"""
generate_summary.py
-------------------
Phase 1 – Step 9 / Deliverable: Create a dataset summary report.

Reads the JSON audit report produced by dataset_audit.py and generates:
  - reports/dataset_summary.md   (human-readable Markdown)
  - reports/class_distribution.csv

Usage:
    python scripts/generate_summary.py --audit reports/dataset_audit.json
"""

import argparse
import csv
import json
from pathlib import Path
from datetime import datetime


def generate_markdown(report: dict, out_md: Path, out_csv: Path):
    classes = report["images_per_class"]
    stats = report["statistics"]

    # Sort by image count descending
    sorted_classes = sorted(classes.items(), key=lambda x: -x[1])
    total = report["total_images"]

    # --- CSV ---
    out_csv.parent.mkdir(parents=True, exist_ok=True)
    with open(out_csv, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["Class", "Image Count", "Percentage (%)"])
        for cls, cnt in sorted_classes:
            writer.writerow([cls, cnt, round(cnt / total * 100, 2) if total else 0])

    # --- Markdown ---
    out_md.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Dataset Summary Report",
        f"> Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}",
        "",
        "## Overview",
        "",
        f"| Metric | Value |",
        f"|--------|-------|",
        f"| Dataset Path | `{report['dataset_path']}` |",
        f"| Total Classes | **{report['num_classes']}** |",
        f"| Total Images | **{total}** |",
        f"| Mean Images / Class | {stats['mean_images_per_class']} |",
        f"| Max Images (single class) | {stats['max_images']} |",
        f"| Min Images (single class) | {stats['min_images']} |",
        f"| Imbalance Ratio (max/min) | {stats['imbalance_ratio_max_to_min']}x |",
        "",
        "## Data Quality",
        "",
        f"| Issue | Count |",
        f"|-------|-------|",
        f"| Corrupted / unreadable images | {len(report['corrupted_images'])} |",
        f"| Exact duplicate groups | {len(report['exact_duplicates'])} |",
        "",
    ]

    if report["corrupted_images"]:
        lines += [
            "### Corrupted / Unreadable Image Paths",
            "",
        ]
        for item in report["corrupted_images"][:20]:
            lines.append(f"- `{item['path']}` — {item.get('error', '')}")
        if len(report["corrupted_images"]) > 20:
            lines.append(f"- _...and {len(report['corrupted_images']) - 20} more (see audit JSON)_")
        lines.append("")

    if report["exact_duplicates"]:
        lines += [
            "### Exact Duplicate Groups (first 10)",
            "",
        ]
        for grp in report["exact_duplicates"][:10]:
            lines.append(f"- MD5 `{grp['md5']}`: {', '.join(f'`{f}`' for f in grp['files'])}")
        lines.append("")

    lines += [
        "## Class Distribution",
        "",
        "| Rank | Class | Images | % of Total |",
        "|------|-------|--------|------------|",
    ]
    for rank, (cls, cnt) in enumerate(sorted_classes, 1):
        pct = round(cnt / total * 100, 2) if total else 0
        lines.append(f"| {rank} | {cls} | {cnt} | {pct}% |")

    lines += [
        "",
        "## Class Imbalance Analysis",
        "",
    ]

    if stats["imbalance_ratio_max_to_min"] > 10:
        lines.append(
            "> ⚠️ **Severe imbalance detected** (ratio > 10x). "
            "Consider oversampling, undersampling, or weighted loss functions."
        )
    elif stats["imbalance_ratio_max_to_min"] > 3:
        lines.append(
            "> ⚡ **Moderate imbalance** (ratio > 3x). "
            "Consider augmentation or class-weighted training."
        )
    else:
        lines.append("> ✅ Dataset is reasonably balanced.")

    lines += [
        "",
        "## Recommended Next Steps",
        "",
        "1. Remove or flag corrupted/duplicate images.",
        "2. Apply data augmentation to under-represented classes.",
        "3. Split dataset into train / validation / test sets (suggested: 70/15/15).",
        "4. Normalise image dimensions and colour channels.",
        "5. Proceed to Phase 2 – Feature Engineering / Model Baseline.",
        "",
        f"---",
        f"*Report auto-generated by `generate_summary.py`*",
    ]

    out_md.write_text("\n".join(lines), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description="Generate dataset summary from audit JSON")
    parser.add_argument("--audit", default="reports/dataset_audit.json", help="Audit JSON file")
    parser.add_argument("--out-md", default="reports/dataset_summary.md", help="Output Markdown path")
    parser.add_argument("--out-csv", default="reports/class_distribution.csv", help="Output CSV path")
    args = parser.parse_args()

    audit_path = Path(args.audit)
    if not audit_path.exists():
        import sys; sys.exit(f"[ERROR] Audit file not found: {audit_path}\nRun dataset_audit.py first.")

    with open(audit_path) as f:
        report = json.load(f)

    out_md = Path(args.out_md)
    out_csv = Path(args.out_csv)

    generate_markdown(report, out_md, out_csv)

    print(f"[DONE] Markdown summary : {out_md.resolve()}")
    print(f"[DONE] CSV distribution : {out_csv.resolve()}")


if __name__ == "__main__":
    main()
